// รหัสอนุญาต "ทำโดยไม่ใช้กล้อง" ประจำวัน (9 พ.ย.: ครูให้ใช้กล้อง 100%)
//   - ใช้เฉพาะเมื่อเครื่องนักเรียนเปิดกล้อง/ตัวตรวจไม่ได้จริง → ครูเดินไปดูเครื่อง แล้วกรอกรหัสให้เอง
//   - รหัส 4 หลัก เปลี่ยนทุกวัน (ตามเวลาเซิร์ฟเวอร์) · ครูดูรหัสได้ที่หน้าครู (แผงติดตามสด)
//   - รอบที่ใช้รหัส = "กล้องใช้ไม่ได้" (camfail) · จับเวลาข้อละ 45 วินาที · ครูเห็น 🚫 ในแผงสดและตาราง
// ─────────────────────────────────────────────────────────────
const SALT = "anukoolnaree|vocab-master|nocam|v1";
export function nocamCode(day: string): string {
  // FNV-1a 32 บิต → 4 หลัก (1000–9999)
  let h = 0x811c9dc5;
  const s = `${SALT}|${day}`;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return String(1000 + (h % 9000));
}

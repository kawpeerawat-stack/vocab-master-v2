// วันที่ (YYYY-MM-DD) เวลาประเทศไทย จากเวลา ms
export const thaiDayOf = (ms: number) => new Date(ms + 7 * 3600000).toISOString().slice(0, 10);

// ทำก่อนวันเปิดของห้องหรือไม่ (openDay = null → ไม่ล็อก ไม่นับว่าล่วงหน้า)
export function doneEarly(day: string | null | undefined, open: string | null | undefined, unlocked: boolean): boolean {
  return !!day && !!open && !unlocked && day < open;
}
